        #region PAT & PMT Generation (ISO/IEC 13818-1 CRC32)

        private void BuildPatPacket(byte[] buffer)
        {
            buffer[0] = 0x47; // Sync Byte
            buffer[1] = 0x40; // Payload Start = 1, PID = 0x0000
            buffer[2] = 0x00;
            buffer[3] = (byte)(0x10 | (_patCc++ & 0x0F));
            buffer[4] = 0x00; // Pointer Field

            int patOffset = 5;
            buffer[patOffset + 0] = 0x00; // table_id = 0x00 (PAT)
            buffer[patOffset + 1] = 0xB0;
            buffer[patOffset + 2] = 0x0D; // section_length = 13 bytes
            buffer[patOffset + 3] = 0x00; // transport_stream_id = 1
            buffer[patOffset + 4] = 0x01;
            buffer[patOffset + 5] = 0xC1; // version_number = 0, current_next = 1
            buffer[patOffset + 6] = 0x00; // section_number = 0
            buffer[patOffset + 7] = 0x00; // last_section_number = 0

            // Program 1 -> PMT PID 0x1000
            buffer[patOffset + 8] = 0x00;
            buffer[patOffset + 9] = 0x01;
            buffer[patOffset + 10] = 0xF0; // PMT PID high (0x10)
            buffer[patOffset + 11] = 0x00; // PMT PID low (0x00)

            uint crc = CalculateCrc32Mpeg(buffer, patOffset, 12);
            buffer[patOffset + 12] = (byte)((crc >> 24) & 0xFF);
            buffer[patOffset + 13] = (byte)((crc >> 16) & 0xFF);
            buffer[patOffset + 14] = (byte)((crc >> 8) & 0xFF);
            buffer[patOffset + 15] = (byte)(crc & 0xFF);

            for (int i = patOffset + 16; i < TS_PACKET_SIZE; i++) buffer[i] = 0xFF;
        }

        private void BuildPmtPacket(byte[] buffer)
        {
            buffer[0] = 0x47;
            buffer[1] = (byte)(0x40 | ((PID_PMT >> 8) & 0x1F)); // Payload Start = 1
            buffer[2] = (byte)(PID_PMT & 0xFF);
            buffer[3] = (byte)(0x10 | (_pmtCc++ & 0x0F));
            buffer[4] = 0x00;

            byte videoStreamType = _codecType switch
            {
                VideoCodecType.H265_HEVC => 0x24,
                VideoCodecType.AV1 => 0x06,
                _ => 0x1B // H.264 / AVC
            };

            int pmtOffset = 5;
            buffer[pmtOffset + 0] = 0x02; // table_id = 0x02 (PMT)
            buffer[pmtOffset + 1] = 0xB0;
            buffer[pmtOffset + 2] = 0x17; // section_length = 23 bytes
            buffer[pmtOffset + 3] = 0x00; // program_number = 1
            buffer[pmtOffset + 4] = 0x01;
            buffer[pmtOffset + 5] = 0xC1;
            buffer[pmtOffset + 6] = 0x00;
            buffer[pmtOffset + 7] = 0x00;

            // PCR PID (0x0100)
            buffer[pmtOffset + 8] = (byte)(0xE0 | ((PID_PCR >> 8) & 0x1F));
            buffer[pmtOffset + 9] = (byte)(PID_PCR & 0xFF);
            buffer[pmtOffset + 10] = 0xF0;
            buffer[pmtOffset + 11] = 0x00;

            // Stream 1: Video Stream (PID 0x0100)
            buffer[pmtOffset + 12] = videoStreamType;
            buffer[pmtOffset + 13] = (byte)(0xE0 | ((PID_VIDEO >> 8) & 0x1F));
            buffer[pmtOffset + 14] = (byte)(PID_VIDEO & 0xFF);
            buffer[pmtOffset + 15] = 0xF0;
            buffer[pmtOffset + 16] = 0x00;

            // Stream 2: Audio Stream (PID 0x0101, AAC ADTS = 0x0F)
            buffer[pmtOffset + 17] = 0x0F;
            buffer[pmtOffset + 18] = (byte)(0xE0 | ((PID_AUDIO >> 8) & 0x1F));
            buffer[pmtOffset + 19] = (byte)(PID_AUDIO & 0xFF);
            buffer[pmtOffset + 20] = 0xF0;
            buffer[pmtOffset + 21] = 0x00;

            uint crc = CalculateCrc32Mpeg(buffer, pmtOffset, 22);
            buffer[pmtOffset + 22] = (byte)((crc >> 24) & 0xFF);
            buffer[pmtOffset + 23] = (byte)((crc >> 16) & 0xFF);
            buffer[pmtOffset + 24] = (byte)((crc >> 8) & 0xFF);
            buffer[pmtOffset + 25] = (byte)(crc & 0xFF);

            for (int i = pmtOffset + 26; i < TS_PACKET_SIZE; i++) buffer[i] = 0xFF;
        }

        /// <summary>
        /// Đóng gói khung AAC ADTS thành các gói MPEG-TS tuân thủ nghiêm ngặt ISO/IEC 13818-1
        /// với PES Header, 33-bit PTS và Adaptation Field padding 0xFF chuẩn xác.
        /// </summary>
        private void BuildAudioPesPackets(byte[] aacFrame, long pts)
        {
            int pesHeaderLen = 14;
            int totalPesLen = pesHeaderLen + aacFrame.Length;
            int pesLengthField = 3 + 5 + aacFrame.Length;

            byte[] pesHeader = new byte[pesHeaderLen];
            pesHeader[0] = 0x00;
            pesHeader[1] = 0x00;
            pesHeader[2] = 0x01;
            pesHeader[3] = 0xC0; // Audio stream 0
            pesHeader[4] = (byte)((pesLengthField >> 8) & 0xFF);
            pesHeader[5] = (byte)(pesLengthField & 0xFF);
            pesHeader[6] = 0x80;
            pesHeader[7] = 0x80; // PTS flag ON
            pesHeader[8] = 0x05; // PTS data length

            // 33-bit PTS
            pesHeader[9] = (byte)(0x21 | (((pts >> 30) & 0x07) << 1));
            pesHeader[10] = (byte)((pts >> 22) & 0xFF);
            pesHeader[11] = (byte)(0x01 | (((pts >> 15) & 0x7F) << 1));
            pesHeader[12] = (byte)((pts >> 7) & 0xFF);
            pesHeader[13] = (byte)(0x01 | ((pts & 0x7F) << 1));

            int frameOffset = 0;
            bool isFirst = true;

            while (frameOffset < aacFrame.Length || isFirst)
            {
                byte[] tsPacket = new byte[TS_PACKET_SIZE];
                tsPacket[0] = 0x47; // Sync Byte

                if (isFirst)
                {
                    tsPacket[1] = (byte)(0x40 | ((PID_AUDIO >> 8) & 0x1F)); // PUSI = 1
                    tsPacket[2] = (byte)(PID_AUDIO & 0xFF);

                    if (totalPesLen >= 184)
                    {
                        // Payload only (0x10)
                        tsPacket[3] = (byte)(0x10 | (_audioCc++ & 0x0F));
                        Array.Copy(pesHeader, 0, tsPacket, 4, pesHeaderLen);
                        int payloadBytes = 184 - pesHeaderLen; // 170 bytes
                        Array.Copy(aacFrame, 0, tsPacket, 4 + pesHeaderLen, payloadBytes);
                        frameOffset += payloadBytes;
                    }
                    else
                    {
                        // Vừa trong 1 gói tin: Bắt buộc dùng Adaptation Field để chèn padding 0xFF
                        int paddingLength = 184 - totalPesLen;
                        tsPacket[3] = (byte)(0x30 | (_audioCc++ & 0x0F)); // AF + Payload
                        tsPacket[4] = (byte)(paddingLength - 1);          // AF length

                        if (paddingLength > 1)
                        {
                            tsPacket[5] = 0x00; // AF flags
                            for (int k = 6; k < 4 + paddingLength; k++)
                            {
                                tsPacket[k] = 0xFF; // Stuffing bytes
                            }
                        }

                        int pesStart = 4 + paddingLength;
                        Array.Copy(pesHeader, 0, tsPacket, pesStart, pesHeaderLen);
                        Array.Copy(aacFrame, 0, tsPacket, pesStart + pesHeaderLen, aacFrame.Length);
                        frameOffset = aacFrame.Length;
                    }

                    isFirst = false;
                }
                else
                {
                    // Continuation packet (PUSI = 0)
                    tsPacket[1] = (byte)((PID_AUDIO >> 8) & 0x1F);
                    tsPacket[2] = (byte)(PID_AUDIO & 0xFF);

                    int remaining = aacFrame.Length - frameOffset;
                    if (remaining >= 184)
                    {
                        tsPacket[3] = (byte)(0x10 | (_audioCc++ & 0x0F));
                        Array.Copy(aacFrame, frameOffset, tsPacket, 4, 184);
                        frameOffset += 184;
                    }
                    else
                    {
                        int paddingLength = 184 - remaining;
                        tsPacket[3] = (byte)(0x30 | (_audioCc++ & 0x0F));
                        tsPacket[4] = (byte)(paddingLength - 1);

                        if (paddingLength > 1)
                        {
                            tsPacket[5] = 0x00;
                            for (int k = 6; k < 4 + paddingLength; k++)
                            {
                                tsPacket[k] = 0xFF;
                            }
                        }

                        int payloadStart = 4 + paddingLength;
                        Array.Copy(aacFrame, frameOffset, tsPacket, payloadStart, remaining);
                        frameOffset += remaining;
                    }
                }

                _packetQueue.Enqueue(tsPacket);
            }
        }

        #endregion

        #region ISO/IEC 13818-1 CRC-32 (0x04C11DB7)

        private static uint CalculateCrc32Mpeg(byte[] data, int offset, int length)
        {
            uint crc = 0xFFFFFFFF;
            for (int i = 0; i < length; i++)
            {
                byte b = data[offset + i];
                for (int bit = 7; bit >= 0; bit--)
                {
                    bool bitVal = ((b >> bit) & 1) == 1;
                    bool msb = (crc & 0x80000000) != 0;
                    crc <<= 1;
                    if (msb ^ bitVal)
                    {
                        crc ^= 0x04C11DB7;
                    }
                }
            }
            return crc;
        }

        #endregion
    }

    /// <summary>
    /// Bitstream Writer hỗ trợ ghi Exp-Golomb (ue, se) và bit-level cho H.264 NAL Units.
    /// </summary>
    internal sealed class H264BitWriter
    {
        private readonly List<byte> _bytes = new(24000);
        private byte _currentByte = 0;
        private int _bitOffset = 0;

        public void WriteBit(int bit)
        {
            _currentByte |= (byte)((bit & 1) << (7 - _bitOffset));
            _bitOffset++;
            if (_bitOffset == 8)
            {
                _bytes.Add(_currentByte);
                _currentByte = 0;
                _bitOffset = 0;
            }
        }

        public void WriteBits(uint value, int numBits)
        {
            for (int i = numBits - 1; i >= 0; i--)
            {
                WriteBit((int)((value >> i) & 1));
            }
        }

        public void WriteByte(byte value)
        {
            WriteBits(value, 8);
        }

        public void WriteRawByte(byte value)
        {
            if (_bitOffset == 0)
            {
                _bytes.Add(value);
            }
            else
            {
                WriteBits(value, 8);
            }
        }

        public void WriteUe(int value)
        {
            uint v = (uint)value + 1;
            int len = 0;
            uint temp = v;
            while (temp > 0)
            {
                len++;
                temp >>= 1;
            }
            for (int i = 0; i < len - 1; i++) WriteBit(0);
            WriteBits(v, len);
        }

        public void WriteSe(int value)
        {
            int codeNum = (value <= 0) ? -2 * value : 2 * value - 1;
            WriteUe(codeNum);
        }

        public void AlignToByte()
        {
            while (_bitOffset != 0)
            {
                WriteBit(0);
            }
        }

        public void WriteTrailingBits()
        {
            WriteBit(1);
            AlignToByte();
        }

        public byte[] ToArray()
        {
            if (_bitOffset > 0)
            {
                _bytes.Add(_currentByte);
                _bitOffset = 0;
                _currentByte = 0;
            }
            return _bytes.ToArray();
        }
    }
