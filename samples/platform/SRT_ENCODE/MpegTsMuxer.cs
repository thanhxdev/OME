            pps.WriteBit(0); // weighted_pred_flag = 0
            pps.WriteBits(0, 2); // weighted_bipred_idc = 0
            pps.WriteSe(0); // pic_init_qp_minus26 = 0
            pps.WriteSe(0); // pic_init_qs_minus26 = 0
            pps.WriteSe(0); // chroma_qp_index_offset = 0
            pps.WriteBit(1); // deblocking_filter_control_present_flag = 1
            pps.WriteBit(0); // constrained_intra_pred_flag = 0
            pps.WriteBit(0); // redundant_pic_cnt_present_flag = 0
            pps.WriteTrailingBits();
            H264_PPS = pps.ToArray();
        }

        public MpegTsMuxer(
            VideoCodecType codecType = VideoCodecType.H264_AVC,
            ColorbarPatternType pattern = ColorbarPatternType.SmpteRp219,
            AudioTestToneType tone = AudioTestToneType.Sine1kHzMinus18dBFS)
        {
            _codecType = codecType;
            CurrentPattern = pattern;
            CurrentTone = tone;
        }

        /// <summary>
        /// Lấy một khối truyền dẫn SRT hoàn chỉnh (7 gói MPEG-TS = 1316 bytes).
        /// Tự động tạo và nạp khung hình hoàn chỉnh vào hàng đợi khi cần.
        /// </summary>
        public byte[] GenerateSrtTransmissionBlock()
        {
            while (_packetQueue.Count < 7)
            {
                EnqueueCompleteBroadcastFrame();
            }

            byte[] srtBlock = new byte[7 * TS_PACKET_SIZE];
            for (int i = 0; i < 7; i++)
            {
                byte[] packet = _packetQueue.Dequeue();
                Array.Copy(packet, 0, srtBlock, i * TS_PACKET_SIZE, TS_PACKET_SIZE);
            }

            return srtBlock;
        }

        private void EnqueueCompleteBroadcastFrame()
        {
            long nowTicks = DateTime.UtcNow.Ticks;
            long pcrBase = (nowTicks / 10) % 0x1FFFFFFFFL; // 33-bit PCR Base @ 90kHz
            int pcrExt = (int)((nowTicks % 10) * 30);      // 9-bit PCR Ext @ 27MHz
            long pts = pcrBase + 4500;                     // 50ms PTS offset

            if (_audioPts == 0)
            {
                _audioPts = pts;
            }

            // 1. Packet PAT (PID 0x0000)
            byte[] patPacket = new byte[TS_PACKET_SIZE];
            BuildPatPacket(patPacket);
            _packetQueue.Enqueue(patPacket);

            // 2. Packet PMT (PID 0x1000)
            byte[] pmtPacket = new byte[TS_PACKET_SIZE];
            BuildPmtPacket(pmtPacket);
            _packetQueue.Enqueue(pmtPacket);

            // 3. Tạo Bitstream H.264 IDR hoàn chỉnh khớp với mẫu Colorbar đang chọn
            byte[] videoFrame = BuildCompleteH264IdrFrame(_frameIndex++, CurrentPattern);

            // 4. Phân mảnh Video Frame thành chuỗi gói tin MPEG-TS (188 bytes/gói)
            int frameOffset = 0;
            bool isFirstPacket = true;

            while (frameOffset < videoFrame.Length)
            {
                byte[] tsPacket = new byte[TS_PACKET_SIZE];
                tsPacket[0] = 0x47; // Sync Byte

                if (isFirstPacket)
                {
                    // Video PES Header Packet (PUSI = 1, PID = 0x0100)
                    tsPacket[1] = 0x41;
                    tsPacket[2] = 0x00;
                    tsPacket[3] = (byte)(0x30 | (_videoCc++ & 0x0F)); // Adaptation Field + Payload

                    // Adaptation Field (7 bytes with PCR)
                    tsPacket[4] = 0x07;
                    tsPacket[5] = 0x10; // PCR Flag ON
                    tsPacket[6] = (byte)((pcrBase >> 25) & 0xFF);
                    tsPacket[7] = (byte)((pcrBase >> 17) & 0xFF);
                    tsPacket[8] = (byte)((pcrBase >> 9) & 0xFF);
                    tsPacket[9] = (byte)((pcrBase >> 1) & 0xFF);
                    tsPacket[10] = (byte)((((byte)(pcrBase & 0x01)) << 7) | 0x7E | ((byte)((pcrExt >> 8) & 0x01)));
                    tsPacket[11] = (byte)(pcrExt & 0xFF);

                    // PES Header (Stream ID = 0xE0 Video)
                    tsPacket[12] = 0x00;
                    tsPacket[13] = 0x00;
                    tsPacket[14] = 0x01;
                    tsPacket[15] = 0xE0;
                    tsPacket[16] = 0x00; // Unbounded length for video
                    tsPacket[17] = 0x00;
                    tsPacket[18] = 0x80;
                    tsPacket[19] = 0x80; // PTS only
                    tsPacket[20] = 0x05;

                    // PTS 33-bit
                    tsPacket[21] = (byte)(0x21 | (((pts >> 30) & 0x07) << 1));
                    tsPacket[22] = (byte)((pts >> 22) & 0xFF);
                    tsPacket[23] = (byte)(0x01 | (((pts >> 15) & 0x7F) << 1));
                    tsPacket[24] = (byte)((pts >> 7) & 0xFF);
                    tsPacket[25] = (byte)(0x01 | ((pts & 0x7F) << 1));

                    int payloadCapacity = TS_PACKET_SIZE - 26; // 162 bytes
                    int bytesToCopy = Math.Min(payloadCapacity, videoFrame.Length - frameOffset);
                    Array.Copy(videoFrame, frameOffset, tsPacket, 26, bytesToCopy);
                    frameOffset += bytesToCopy;

                    for (int i = 26 + bytesToCopy; i < TS_PACKET_SIZE; i++) tsPacket[i] = 0xFF;

                    isFirstPacket = false;
                }
                else
                {
                    // Video Continuation Packet (PUSI = 0)
                    tsPacket[1] = 0x01;
                    tsPacket[2] = 0x00;

                    int remainingBytes = videoFrame.Length - frameOffset;
                    if (remainingBytes >= 184)
                    {
                        // Payload only (0x10)
                        tsPacket[3] = (byte)(0x10 | (_videoCc++ & 0x0F));
                        Array.Copy(videoFrame, frameOffset, tsPacket, 4, 184);
                        frameOffset += 184;
                    }
                    else
                    {
                        // Gói tin cuối cùng của khung hình: sử dụng Adaptation Field để chèn padding 0xFF
                        int paddingLength = 184 - remainingBytes;
                        tsPacket[3] = (byte)(0x30 | (_videoCc++ & 0x0F)); // Adaptation Field + Payload
                        tsPacket[4] = (byte)(paddingLength - 1);          // Adaptation field length
                        if (paddingLength > 1)
                        {
                            tsPacket[5] = 0x00; // Flags
                            for (int k = 6; k < 5 + paddingLength; k++) tsPacket[k] = 0xFF;
                        }

                        int payloadStart = 4 + paddingLength;
                        Array.Copy(videoFrame, frameOffset, tsPacket, payloadStart, remainingBytes);
                        frameOffset += remainingBytes;
                    }
                }

                _packetQueue.Enqueue(tsPacket);
            }

            // 5. Nạp gói tin Audio PES (AAC ADTS) theo nhịp đồng bộ PTS chính xác (1024 samples @ 48kHz = 1920 ticks @ 90kHz)
            while (_audioPts <= pts + 1920)
            {
                byte[] aacFrame = GetCurrentAacFrame();
                BuildAudioPesPackets(aacFrame, _audioPts);
                _audioPts += 1920; // 1024 / 48000 * 90000 = 1920 ticks
            }
        }

        private byte[] GetCurrentAacFrame()
        {
            long idx = _audioFrameCounter++;
            return CurrentTone switch
            {
                AudioTestToneType.Sine1kHzMinus18dBFS or AudioTestToneType.Sine1kHzMinus20dBFS =>
                    AAC_SINE_1KHZ_FRAMES[idx % AAC_SINE_1KHZ_FRAMES.Length],

                AudioTestToneType.Glits400Hz =>
                    AAC_GLITS_400HZ_FRAMES[idx % AAC_GLITS_400HZ_FRAMES.Length],

                AudioTestToneType.EbuToneIdent =>
                    // EBU R49: Phát tone 3 frame, im lặng 1 frame
                    (idx % 4 == 3) ? AAC_SILENCE_FRAME : AAC_SINE_1KHZ_FRAMES[idx % AAC_SINE_1KHZ_FRAMES.Length],

                _ => AAC_SINE_1KHZ_FRAMES[idx % AAC_SINE_1KHZ_FRAMES.Length]
            };
        }

        #region H.264 I_PCM Macroblock Bitstream Generator (Matching Selected Pattern)

        private byte[] BuildCompleteH264IdrFrame(long frameNum, ColorbarPatternType pattern)
        {
            var frameBytes = new List<byte>(24000);

            // 1. AUD (Access Unit Delimiter)
            frameBytes.AddRange(new byte[] { 0x00, 0x00, 0x00, 0x01, 0x09, 0x10 });

            // 2. SPS
            frameBytes.AddRange(new byte[] { 0x00, 0x00, 0x00, 0x01 });
            frameBytes.AddRange(H264_SPS);

            // 3. PPS
            frameBytes.AddRange(new byte[] { 0x00, 0x00, 0x00, 0x01 });
            frameBytes.AddRange(H264_PPS);

            // 4. IDR Slice NAL (0x65)
            frameBytes.AddRange(new byte[] { 0x00, 0x00, 0x00, 0x01 });

            var slice = new H264BitWriter();
            slice.WriteByte(0x65); // NAL Header: nal_ref_idc=3, nal_unit_type=5 (IDR)

            // Slice Header
            slice.WriteUe(0); // first_mb_in_slice = 0
            slice.WriteUe(7); // slice_type = 7 (I-slice, all I)
            slice.WriteUe(0); // pic_parameter_set_id = 0
            slice.WriteBits(0, 4); // frame_num = 0 (IDR frame)
            slice.WriteUe(0); // idr_pic_id = 0
            slice.WriteBits(0, 4); // pic_order_cnt_lsb = 0
            slice.WriteBit(0); // no_output_of_prior_pics_flag = 0
            slice.WriteBit(0); // long_term_reference_flag = 0
            slice.WriteSe(0); // slice_qp_delta = 0
            slice.WriteUe(1); // disable_deblocking_filter_idc = 1

            // Ghi 60 Macroblocks (10x6) ở chế độ I_PCM (Raw YUV samples)
            for (int mbY = 0; mbY < MB_HEIGHT; mbY++)
            {
                for (int mbX = 0; mbX < MB_WIDTH; mbX++)
                {
                    // mb_type = 25 (I_PCM)
                    slice.WriteUe(25);
                    slice.AlignToByte();

                    // 256 bytes Luma Y (16x16)
                    for (int y = 0; y < 16; y++)
                    {
                        int globalY = mbY * 16 + y;
                        for (int x = 0; x < 16; x++)
                        {
                            int globalX = mbX * 16 + x;
                            var (yVal, _, _) = GetPatternColor(pattern, globalX, globalY, frameNum);
                            slice.WriteRawByte(yVal);
                        }
                    }

                    // 64 bytes Chroma Cb (8x8)
                    for (int v = 0; v < 8; v++)
                    {
                        int globalY = mbY * 16 + v * 2;
                        for (int u = 0; u < 8; u++)
                        {
                            int globalX = mbX * 16 + u * 2;
                            var (_, uVal, _) = GetPatternColor(pattern, globalX, globalY, frameNum);
                            slice.WriteRawByte(uVal);
                        }
                    }

                    // 64 bytes Chroma Cr (8x8)
                    for (int v = 0; v < 8; v++)
                    {
                        int globalY = mbY * 16 + v * 2;
                        for (int u = 0; u < 8; u++)
                        {
                            int globalX = mbX * 16 + u * 2;
                            var (_, _, vVal) = GetPatternColor(pattern, globalX, globalY, frameNum);
                            slice.WriteRawByte(vVal);
                        }
                    }
                }
            }

            slice.WriteTrailingBits();
            frameBytes.AddRange(slice.ToArray());

            return frameBytes.ToArray();
        }

        /// <summary>
        /// Xác định mã màu (Y, U, V) chính xác theo tọa độ pixel (0..159, 0..89) và mẫu hình được chọn
        /// </summary>
        private static (byte Y, byte U, byte V) GetPatternColor(ColorbarPatternType pattern, int x, int y, long frameNum)
        {
            // Subtle Heartbeat Indicator ở góc trên cùng bên phải (152..156, 2..6) để ffplay nhận diện stream đang chạy
            if (x >= 152 && x <= 156 && y >= 2 && y <= 6)
            {
                return ((frameNum / 15) % 2 == 0) ? ((byte)235, (byte)128, (byte)128) : ((byte)16, (byte)128, (byte)128);
            }

            switch (pattern)
            {
                case ColorbarPatternType.SmpteRp219:
                    return GetSmpteRp219Color(x, y);

                case ColorbarPatternType.Ebu100Percent:
                    return GetEbu100Color(x, y);

                case ColorbarPatternType.GridAlignment:
                    return GetGridAlignmentColor(x, y);

                default:
                    return GetSmpteRp219Color(x, y);
            }
        }

        private static (byte Y, byte U, byte V) GetSmpteRp219Color(int x, int y)
        {
            // Top 67% (y: 0..59): 7 thanh màu 75% Intensity (White, Yellow, Cyan, Green, Magenta, Red, Blue)
            if (y < 60)
            {
                int barIdx = (x * 7) / FRAME_WIDTH;
                return barIdx switch
                {
                    0 => ((byte)180, (byte)128, (byte)128), // 75% White
                    1 => ((byte)162, (byte)44,  (byte)142), // 75% Yellow
                    2 => ((byte)131, (byte)156, (byte)44),  // 75% Cyan
                    3 => ((byte)112, (byte)72,  (byte)58),  // 75% Green
                    4 => ((byte)84,  (byte)184, (byte)198), // 75% Magenta
                    5 => ((byte)65,  (byte)100, (byte)212), // 75% Red
                    6 => ((byte)35,  (byte)212, (byte)114), // 75% Blue
                    _ => ((byte)180, (byte)128, (byte)128)
                };
            }

            // Middle 8% (y: 60..67): Castellation Bars
            if (y < 68)
            {
                int barIdx = (x * 7) / FRAME_WIDTH;
                return barIdx switch
                {
                    0 => ((byte)35,  (byte)212, (byte)114), // 75% Blue
                    1 => ((byte)16,  (byte)128, (byte)128), // Black
                    2 => ((byte)84,  (byte)184, (byte)198), // 75% Magenta
                    3 => ((byte)16,  (byte)128, (byte)128), // Black
                    4 => ((byte)131, (byte)156, (byte)44),  // 75% Cyan
                    5 => ((byte)16,  (byte)128, (byte)128), // Black
                    6 => ((byte)180, (byte)128, (byte)128), // 75% White
                    _ => ((byte)16,  (byte)128, (byte)128)
                };
            }

            // Bottom 25% (y: 68..89): -I, 100% White, +Q, Black, Pluge Pulses, Black
            if (x < 27) return ((byte)70, (byte)156, (byte)90);    // -I patch (Cyan-ish)
            if (x < 54) return ((byte)235, (byte)128, (byte)128);  // 100% White
            if (x < 80) return ((byte)40, (byte)170, (byte)150);   // +Q patch (Purple)
            if (x < 107) return ((byte)16, (byte)128, (byte)128);  // 0% Black

            // Pluge Pulses
            if (x < 134)
            {
                if (x < 116) return ((byte)12, (byte)128, (byte)128); // -2% Sub-black
                if (x < 125) return ((byte)16, (byte)128, (byte)128); // 0% Black
                return ((byte)22, (byte)128, (byte)128);              // +2% Above-black
            }

            return ((byte)16, (byte)128, (byte)128); // 0% Black
        }

        private static (byte Y, byte U, byte V) GetEbu100Color(int x, int y)
        {
            int barIdx = (x * 8) / FRAME_WIDTH;
            return barIdx switch
            {
                0 => ((byte)235, (byte)128, (byte)128), // 100% White
                1 => ((byte)210, (byte)16,  (byte)146), // 100% Yellow
                2 => ((byte)170, (byte)166, (byte)16),  // 100% Cyan
                3 => ((byte)145, (byte)54,  (byte)34),  // 100% Green
                4 => ((byte)106, (byte)202, (byte)222), // 100% Magenta
                5 => ((byte)81,  (byte)90,  (byte)240), // 100% Red
                6 => ((byte)41,  (byte)240, (byte)110), // 100% Blue
                _ => ((byte)16,  (byte)128, (byte)128)  // 0% Black
            };
        }

        private static (byte Y, byte U, byte V) GetGridAlignmentColor(int x, int y)
        {
            bool isGridLine = (x % 16 == 0) || (y % 16 == 0) || (x == 80) || (y == 45) || (x == 0) || (x == 159) || (y == 0) || (y == 89);
            return isGridLine ? ((byte)235, (byte)128, (byte)128) : ((byte)16, (byte)128, (byte)128);
        }

